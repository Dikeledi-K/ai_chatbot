function normalizeExportText(value) {
  if (Array.isArray(value)) return value.join('\n\n').trim();
  const text = String(value ?? '').replace(/\r/g, '').trim();
  return text;
}

function createToast(message) {
  let toast = document.querySelector('.export-toast');
  if (!toast) {
    toast = document.createElement('div');
    toast.className = 'export-toast';
    document.body.appendChild(toast);
  }

  toast.textContent = message;
  toast.classList.add('visible');
  clearTimeout(toast.dataset.hideTimer);
  toast.dataset.hideTimer = String(setTimeout(() => {
    toast.classList.remove('visible');
  }, 2200));
}

function buildExportFileName(prefix = 'studybuddy', title = 'export') {
  const date = new Date().toISOString().slice(0, 10);
  const safeTitle = String(title || prefix || 'studybuddy')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'export';
  return `${String(prefix || 'studybuddy').toLowerCase().replace(/[^a-z0-9]+/g, '-') || 'studybuddy'}-${safeTitle}-${date}`;
}

function exportTextFile(fileName, content) {
  const text = normalizeExportText(content);
  if (!text) throw new Error('There is no readable text to export yet.');

  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${fileName}.txt`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

function exportPdfFile(fileName, title, content) {
  const text = normalizeExportText(content);
  if (!text) throw new Error('There is no readable content to export yet.');

  if (!window.jspdf?.jsPDF) {
    throw new Error('PDF export is unavailable right now. Please try again in a moment.');
  }

  const { jsPDF } = window.jspdf;
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 48;
  const maxWidth = pageWidth - margin * 2;
  let cursorY = 72;

  doc.setFillColor(249, 115, 22);
  doc.roundedRect(margin, 24, pageWidth - margin * 2, 30, 8, 8, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text(title || 'StudyBuddy export', margin + 12, 46);

  doc.setTextColor(25, 25, 25);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text('Generated by StudyBuddy AI', margin, 76);
  cursorY = 104;

  const paragraphs = text
    .split(/\n{2,}/)
    .map((paragraph) => paragraph.trim())
    .filter(Boolean);

  const headingLines = doc.splitTextToSize(title || 'StudyBuddy export', maxWidth);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  const headerBlock = headingLines[0] || 'StudyBuddy export';
  doc.text(headerBlock, margin, cursorY);
  cursorY += 18;

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');

  for (const paragraph of paragraphs) {
    const lines = doc.splitTextToSize(paragraph, maxWidth);
    if (cursorY + lines.length * 16 > pageHeight - margin) {
      doc.addPage();
      cursorY = margin;
    }

    doc.text(lines, margin, cursorY);
    cursorY += lines.length * 16 + 12;
  }

  doc.save(`${fileName}.pdf`);
}

export function exportStudyDocument({ title, content, kind = 'studybuddy' }) {
  const safeTitle = String(title || 'StudyBuddy export').trim();
  const normalizedContent = normalizeExportText(content);
  if (!safeTitle || !normalizedContent) {
    throw new Error('There is no readable content to export yet.');
  }

  const fileName = buildExportFileName(kind, safeTitle);
  return { fileName, title: safeTitle, content: normalizedContent };
}

export function downloadExportAs({ title, content, kind = 'studybuddy', format = 'txt' }) {
  const exportInfo = exportStudyDocument({ title, content, kind });

  if (format === 'pdf') {
    exportPdfFile(exportInfo.fileName, exportInfo.title, exportInfo.content);
    return;
  }

  exportTextFile(exportInfo.fileName, exportInfo.content);
}

export function attachExportMenu({ trigger, title, content, kind = 'studybuddy' }) {
  if (!trigger) return;

  const wrapper = document.createElement('div');
  wrapper.className = 'export-trigger-wrap';

  const menu = document.createElement('div');
  menu.className = 'export-menu hidden';
  menu.innerHTML = `
    <button type="button" class="export-menu__item" data-export-format="txt">Download as TXT</button>
    <button type="button" class="export-menu__item" data-export-format="pdf">Download as PDF</button>
  `;

  wrapper.append(trigger, menu);
  trigger.addEventListener('click', (event) => {
    event.stopPropagation();
    menu.classList.toggle('hidden');
  });

  menu.addEventListener('click', (event) => {
    const option = event.target.closest('[data-export-format]');
    if (!option) return;

    event.stopPropagation();
    const format = option.dataset.exportFormat;
    try {
      downloadExportAs({ title, content, kind, format });
      createToast('Download started');
      menu.classList.add('hidden');
    } catch (error) {
      createToast(error.message || 'The export could not be created.');
    }
  });

  document.addEventListener('click', () => menu.classList.add('hidden'));

  return wrapper;
}
